#!/usr/bin/env python3
"""Generate packages/shared/src/utils/aws-zones.ts from AWS.

Writes directly to the file by default:

    python3 scripts/generate_aws_zones.py

Pass `--output -` to write TypeScript to stdout instead.

Regions not enabled for the selected account remain present with an empty
`defaultZone`, because AWS does not expose their availability zones until the
region is enabled. Wavelength Zones are excluded.
"""

import argparse
import json
import subprocess
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

DEFAULT_PROFILE = "tabot-dev"
DEFAULT_OUTPUT = (
    Path(__file__).resolve().parents[1]
    / "packages"
    / "shared"
    / "src"
    / "utils"
    / "aws-zones.ts"
)
CONTROL_REGION = "us-east-1"
ENABLED_REGION_STATUSES = {"opt-in-not-required", "opted-in"}
INCLUDED_ZONE_TYPES = {"availability-zone", "local-zone"}


def aws(profile: str, region: str, *args: str) -> dict[str, Any]:
    command = [
        "aws",
        "--profile",
        profile,
        "--region",
        region,
        "--output",
        "json",
        *args,
    ]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip()
        raise RuntimeError(f"{' '.join(command)} failed: {detail}")
    return json.loads(result.stdout)


def fetch_regions(profile: str) -> list[dict[str, str]]:
    response = aws(
        profile,
        CONTROL_REGION,
        "ec2",
        "describe-regions",
        "--all-regions",
    )
    return sorted(response["Regions"], key=lambda region: region["RegionName"])


def fetch_zones(profile: str, region: str) -> list[dict[str, str]]:
    response = aws(
        profile,
        region,
        "ec2",
        "describe-availability-zones",
        "--all-availability-zones",
    )
    return sorted(
        (
            zone
            for zone in response["AvailabilityZones"]
            if zone["ZoneType"] in INCLUDED_ZONE_TYPES
        ),
        key=lambda zone: zone["ZoneName"],
    )


def group_zones(
    region: str,
    zones: Sequence[dict[str, str]],
) -> dict[str, dict[str, str]]:
    groups: dict[str, dict[str, str]] = {"defaultZone": {}}

    for zone in zones:
        zone_name = zone["ZoneName"]
        zone_type = zone["ZoneType"]

        if zone_type == "availability-zone":
            group_key = "defaultZone"
            availability_zone = zone_name.removeprefix(region)
        else:
            group_name = zone["GroupName"]
            expected_prefix = f"{region}-"
            if not group_name.startswith(expected_prefix):
                raise ValueError(
                    f"Unexpected Local Zone group {group_name!r} for {region!r}"
                )
            if not zone_name.startswith(group_name):
                raise ValueError(
                    f"Zone {zone_name!r} does not belong to group {group_name!r}"
                )
            group_key = group_name.removeprefix(expected_prefix)
            availability_zone = zone_name.removeprefix(group_name)

        if not availability_zone:
            raise ValueError(f"Could not derive availability-zone key from {zone_name!r}")

        groups.setdefault(group_key, {})[availability_zone] = zone_name

    return groups


def render_zone_group(group_key: str, zones: dict[str, str]) -> str:
    property_name = "defaultZone" if group_key == "defaultZone" else json.dumps(group_key)
    if not zones:
        return f"\t\t{property_name}: {{}},"

    ordered_zones = sorted(zones.items())
    default_zone = ordered_zones[0][1]
    lines = [
        f"\t\t{property_name}: {{",
        f'\t\t\tdefaultAvailabilityZone: {json.dumps(default_zone)},',
    ]
    lines.extend(
        f"\t\t\t{availability_zone}: {json.dumps(zone_name)},"
        for availability_zone, zone_name in ordered_zones
    )
    lines.append("\t\t},")
    return "\n".join(lines)


def render_region(region: str, groups: dict[str, dict[str, str]]) -> str:
    ordered_group_keys = ["defaultZone", *sorted(groups.keys() - {"defaultZone"})]
    rendered_groups = "\n".join(
        render_zone_group(group_key, groups[group_key])
        for group_key in ordered_group_keys
    )
    return f'\t{json.dumps(region)}: {{\n{rendered_groups}\n\t}},'


def generate(profile: str) -> str:
    rendered_regions: list[str] = []

    for region_data in fetch_regions(profile):
        region = region_data["RegionName"]
        if region_data["OptInStatus"] in ENABLED_REGION_STATUSES:
            groups = group_zones(region, fetch_zones(profile, region))
        else:
            groups = {"defaultZone": {}}
        rendered_regions.append(render_region(region, groups))

    regions = "\n".join(rendered_regions)
    return f"""// This file is generated by scripts/generate_aws_zones.py.
// Do not edit manually.

export type AwsZone = {{
\t[Region in keyof typeof awsZones]: {{
\t\t[ZoneGroup in keyof (typeof awsZones)[Region]]: (typeof awsZones)[Region][ZoneGroup] extends infer Zones
\t\t\t? Zones[keyof Zones]
\t\t\t: never;
\t}}[keyof (typeof awsZones)[Region]];
}}[keyof typeof awsZones];

export const awsZones = {{
{regions}
}} as const;
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--profile",
        default=DEFAULT_PROFILE,
        help=f"AWS CLI profile (default: {DEFAULT_PROFILE})",
    )
    parser.add_argument(
        "--output",
        default=str(DEFAULT_OUTPUT),
        help="output file, or - for stdout (default: packages/shared/src/utils/aws-zones.ts)",
    )
    args = parser.parse_args()

    try:
        generated = generate(args.profile)
        if args.output == "-":
            sys.stdout.write(generated)
        else:
            output = Path(args.output)
            output.write_text(generated)
            print(f"Wrote {output}")
    except (KeyError, OSError, ValueError, RuntimeError, json.JSONDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        raise SystemExit(1) from error


if __name__ == "__main__":
    main()
